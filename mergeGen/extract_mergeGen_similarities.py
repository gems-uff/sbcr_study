'''

Script to calculate the similarity between generated candidates by MergeGen, the solution and the chunks parents (using LCS)

Load the complete dataset to get the parents of each chunk
Given a folder (the folder where the outputs of MergeGen are. Usually in OUTPUT/model_name/test_OUTPUT):
    Access the folder 'FAIL'
        For each file in this folder:
            Open the file
                Separate the candidate generated by MergeGen (first element of the list that comes after 'output:')
                The reference (comes after ref_dataloader:)
                The time (comes after time:)
            Calculate the similarities (using LCS):
                between the candidate and the parents
                between the candidate and the solution (truncated and complete)
            Save the collected data
            
    Access the folder 'SUCCEED'
        For each file in this folder:
            Repeat the process above
        Save the collected data          

Example file
ref_dataloader:
fillRepairReadsValues(nodeValues, key, node, fetched); failureDetector.recordSuccess(node);
---------------------------------
output:
['if(repairReads) { for(Versioned<byte[]> f: fetched) nodeValues.add(new NodeValue<ByteArray, byte[]>(node.getId(), key, f)); } failureDetector.recordSuccess(node);', 'failureDetector.recordSuccess(node);', 'if(repairReads) { for(Versioned<byte[]> f: fetched) nodeValues.add(new NodeValue<ByteArray, byte[]>(node.getId(), key, f)); } failureDetector.recordFailure(node);']
---------------------------------
time: 0.349259 s

'''
def extract_data(file_path):
    try:
        with open(file_path, 'r') as file:
            lines = file.readlines()
            reference = lines[1].strip()
            output = eval(lines[4].strip())[0]
            time = float(lines[6].split(' ')[1])
    except:
        print('Error reading file: ', file_path)
        return None, None, None
    return output, reference, time

def analyze_folder(folder_path, max_resolve_length):
    if max_resolve_length is not None:
        max_resolve_length = int(max_resolve_length)
    
    files = os.listdir(folder_path)
    outputs = []
    references = []
    times = []
    chunk_indexes = []
    complete_references = []
    v1s = []
    v2s = []
        
    for file in files:
        output, reference, time = extract_data(folder_path + '/' + file)
        complete_reference = get_original_resolution(file)
        v1 = get_parent_v1(file)
        v2 = get_parent_v2(file)
        if output is not None:
            if max_resolve_length is not None:
                outputs.append(output[:max_resolve_length])
                references.append(reference[:max_resolve_length])
            else:
                outputs.append(output)
                references.append(reference)
            times.append(time)
            chunk_indexes.append(file)
            complete_references.append(complete_reference)
            v1s.append(v1)
            v2s.append(v2)
    return outputs, references, times, chunk_indexes, complete_references, v1s, v2s

def get_lcs(text1,text2):
    res = pylcs.lcs_sequence_idx(text1, text2)
    lcs = ''.join([text2[i] for i in res if i != -1])
    return lcs

def get_gestalt(file1_text,file2_text):
    try:
        if file1_text == file2_text:
            return 1
        return 2*len(get_lcs(file1_text, file2_text)) / (len(file1_text) + len(file2_text))
    except Exception as e:
        print(e)
        return 0

def get_aggregated_similarity(v1_gestalt, v2_gestalt):
    try:
        return (v1_gestalt + v2_gestalt) / 2
    except Exception as e:
        print(e)
        return -1

def get_original_resolution(chunk_index):
    return df_complete.iloc[int(chunk_index)]['all_raw_res']

def get_parent_v1(chunk_index):
    return df_complete.iloc[int(chunk_index)]['all_raw_a']

def get_parent_v2(chunk_index):
    return df_complete.iloc[int(chunk_index)]['all_raw_b']

def calculate_similarity(output, reference):
    return get_gestalt(output, reference)

def calculate_similarity_without_linebreaks(output, complete_reference):
    return get_gestalt(output.replace(' ','').replace('\n',''), complete_reference.replace(' ','').replace('\n',''))

def main(model, dataset, max_resolve_length):
    path = 'OUTPUT/' + dataset + '/model_' + model + '/test_OUTPUT'
    fail_path = path + '/FAIL'
    succeed_path = path + '/SUCCEED'
    fail_outputs, fail_references, fail_times, fail_chunk_indexes, fail_complete_references, fail_v1s, fail_v2s = analyze_folder(fail_path, max_resolve_length)
    succeed_outputs, succeed_references, succeed_times, succeed_chunk_indexes, succeed_complete_references, succeed_v1s, succeed_v2s = analyze_folder(succeed_path, max_resolve_length)
    fail_similarities = []
    succeed_similarities = []
    fail_complete_similarities = []
    succeed_complete_similarities = []
    fail_v1_similarities = []
    fail_v2_similarities = []
    succeed_v1_similarities = []
    succeed_v2_similarities = []
    fail_parents_aggregated_similarities = []
    succeed_parents_aggregated_similarities = []

        
    for i in range(len(fail_outputs)):
        fail_similarities.append(calculate_similarity(fail_outputs[i], fail_references[i]))
        fail_complete_similarities.append(calculate_similarity_without_linebreaks(fail_outputs[i], fail_complete_references[i]))
        fail_v1_similarities.append(calculate_similarity_without_linebreaks(fail_outputs[i], fail_v1s[i]))
        fail_v2_similarities.append(calculate_similarity_without_linebreaks(fail_outputs[i], fail_v2s[i]))
        fail_parents_aggregated_similarities.append(get_aggregated_similarity(fail_v1_similarities[i], fail_v2_similarities[i]))

    for i in range(len(succeed_outputs)):
        succeed_similarities.append(calculate_similarity(succeed_outputs[i], succeed_references[i]))
        succeed_complete_similarities.append(calculate_similarity_without_linebreaks(succeed_outputs[i], succeed_complete_references[i]))
        succeed_v1_similarities.append(calculate_similarity_without_linebreaks(succeed_outputs[i], succeed_v1s[i]))
        succeed_v2_similarities.append(calculate_similarity_without_linebreaks(succeed_outputs[i], succeed_v2s[i]))
        succeed_parents_aggregated_similarities.append(get_aggregated_similarity(succeed_v1_similarities[i], succeed_v2_similarities[i]))
    data = []
    for i in range(len(fail_outputs)):
        data.append((fail_chunk_indexes[i], fail_similarities[i], fail_complete_similarities[i], fail_times[i], fail_v1_similarities[i], fail_v2_similarities[i], fail_parents_aggregated_similarities[i], 'FAIL'))
    for i in range(len(succeed_outputs)):
        data.append((succeed_chunk_indexes[i], succeed_similarities[i], succeed_complete_similarities[i], succeed_times[i], succeed_v1_similarities[i], succeed_v2_similarities[i], succeed_parents_aggregated_similarities[i], 'SUCCEED'))
    pd.DataFrame(data, columns=['chunk_index', 'similarity', 'complete_similarity', 'time', 'v1_similarity', 'v2_similarity', 'parents_similarity', 'result']).to_csv(f'RESULTS/mergeGen_{dataset}_model_{model}_similarities.csv', index=False)
    # print('Fail similarities:', fail_similarities)
    # print('Succeed similarities:', succeed_similarities)
